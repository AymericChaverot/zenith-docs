/** Built-in strings for a language, overridden by the `translations` option. */
export function getTranslations(lang: string, overrides?: Record<string, string>): Translations {
  const subtag = lang.split('-')[0]!.toLowerCase();
  return {
    ...DEFAULT_TRANSLATIONS,
    ...BUILTIN_TRANSLATIONS[subtag],
    ...overrides,
  } as Translations;
}
